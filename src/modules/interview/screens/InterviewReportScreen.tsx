import React, { useState } from "react";
import { Linking, Platform, View } from "react-native";
import { useRoute, RouteProp } from "@react-navigation/native";
import { useMutation, useQuery } from "@tanstack/react-query";
import { interviewApi } from "@modules/interview/api/interviewApi";
import { useReport } from "@modules/interview/hooks/useInterviews";
import { InterviewsStackParamList } from "@modules/interview/InterviewsNavigator";
import { ROUND_LABEL, RoundReport, Report } from "@modules/interview/types";
import { apiErrorCode, apiErrorMessage } from "@api/apiClient";
import { formatDate, titleCase } from "@shared/format";
import { palette, radius, numeric } from "@shared/designSystem";
import {
  Screen,
  Card,
  Text,
  VStack,
  HStack,
  Button,
  Banner,
  Skeleton,
  ErrorState,
  SectionHeader,
} from "@shared/ui";

const scoreTone = (score: number) =>
  score >= 70 ? "success" : score >= 50 ? "warning" : "danger";

export default function InterviewReportScreen() {
  const { id } = useRoute<RouteProp<InterviewsStackParamList, "InterviewReport">>().params;
  const { data, isLoading, isError, error, refetch, isFetching } = useReport(id);

  return (
    <Screen
      title="Interview report"
      subtitle={
        data
          ? `${data.interview.targetRole} · completed ${formatDate(data.interview.completedAt)}`
          : undefined
      }
      back="Back to interviews"
    >
      {isLoading ? (
        <Skeleton height={240} />
      ) : isError || !data ? (
        apiErrorCode(error) === "REPORT_NOT_READY" ? (
          <Banner
            tone="info"
            title="Not finished yet"
            message="The report appears once all rounds are complete."
          />
        ) : (
          <ErrorState
            error={error}
            title="Couldn't load the report"
            onRetry={() => void refetch()}
            retrying={isFetching}
          />
        )
      ) : (
        <VStack gap={4}>
          {data.provisional ? (
            <Banner
              tone="info"
              title="Your scores are being prepared"
              message="Each round is scored after it ends, usually within a minute. This page updates by itself. Your transcript is below."
            />
          ) : (
            <Overall report={data} />
          )}
          {data.rounds.map((r) => (
            <RoundSection key={r.id} interviewId={id} round={r} />
          ))}
          <Text variant="caption" tone="tertiary" style={{ marginTop: 12 }}>
            Scores and feedback are generated by AI from your transcript for
            practice. They are not an employment decision.
          </Text>
        </VStack>
      )}
    </Screen>
  );
}

function Overall({ report }: { report: Report }) {
  return (
    <Card>
      <VStack gap={12}>
        <HStack gap={16} align="center" wrap>
          <VStack gap={0}>
            <Text variant="overline" tone="tertiary">
              Overall score
            </Text>
            <Text
              variant="display-lg"
              tone={scoreTone(report.overallScore ?? 0)}
              style={numeric}
            >
              {report.overallScore ?? "-"}
              <Text variant="body" tone="tertiary">
                {" "}
                / 100
              </Text>
            </Text>
          </VStack>
          <HStack gap={16} wrap>
            {report.rounds.map((r) => (
              <VStack key={r.id} gap={0}>
                <Text variant="caption" tone="tertiary">
                  {ROUND_LABEL[r.roundType]}
                </Text>
                <Text variant="h2" style={numeric}>
                  {r.score ?? "-"}
                </Text>
              </VStack>
            ))}
          </HStack>
        </HStack>
        {report.summary ? <Text variant="body">{report.summary}</Text> : null}
        <BulletList title="Recurring strengths" items={report.strengths} />
        <BulletList title="Priority improvements" items={report.improvementAreas} />
        <BulletList title="Practise next" items={report.practiceTopics} />
      </VStack>
    </Card>
  );
}

function BulletList({ title, items }: { title: string; items: string[] }) {
  if (!items.length) return null;
  return (
    <VStack gap={4}>
      <Text variant="label" tone="secondary">
        {title}
      </Text>
      {items.map((s) => (
        <Text key={s} variant="body-sm">
          {"• "}
          {s}
        </Text>
      ))}
    </VStack>
  );
}

function RoundSection({ interviewId, round }: { interviewId: string; round: RoundReport }) {
  const scored = round.evaluationStatus === "final";
  return (
    <>
      <SectionHeader
        title={ROUND_LABEL[round.roundType]}
        count={
          scored
            ? `${round.score} / 100`
            : round.endReason
              ? titleCase(round.endReason)
              : undefined
        }
      />
      {scored ? (
        <Card>
          <VStack gap={12}>
            {round.dimensions.map((d) => (
              <VStack key={d.key} gap={4}>
                <HStack justify="space-between" align="center" gap={8}>
                  <Text variant="label">
                    {d.label}
                    <Text variant="caption" tone="tertiary">
                      {"  "}
                      weight {d.weight}%
                    </Text>
                  </Text>
                  <Text variant="label" tone={scoreTone(d.score)} style={numeric}>
                    {d.score}
                  </Text>
                </HStack>
                <View
                  style={{
                    height: 6,
                    borderRadius: radius.full,
                    backgroundColor: palette.surface.sunken,
                    overflow: "hidden",
                  }}
                  accessibilityRole="progressbar"
                  accessibilityValue={{ min: 0, max: 100, now: d.score }}
                >
                  <View
                    style={{
                      width: `${d.score}%`,
                      height: 6,
                      backgroundColor: palette[scoreTone(d.score)].text,
                    }}
                  />
                </View>
                {d.evidence ? (
                  <Text variant="body-sm" tone="secondary">
                    {d.evidence}
                  </Text>
                ) : null}
              </VStack>
            ))}
            {round.feedback ? <Text variant="body">{round.feedback}</Text> : null}
            <BulletList title="What went well" items={round.strengths} />
            <BulletList title="What to improve" items={round.improvements} />
          </VStack>
        </Card>
      ) : null}
      {round.hasRecording ? <RecordingPlayer interviewId={interviewId} roundId={round.id} /> : null}
      <Transcript interviewId={interviewId} roundId={round.id} />
    </>
  );
}

/** Fetches a short-lived link only when asked - it is never stored or pre-loaded. */
function RecordingPlayer({ interviewId, roundId }: { interviewId: string; roundId: string }) {
  const [url, setUrl] = useState<string | null>(null);
  const access = useMutation({
    mutationFn: () => interviewApi.recordingAccess(interviewId, roundId),
    onSuccess: (a) => {
      if (Platform.OS === "web") setUrl(a.url);
      else void Linking.openURL(a.url);
    },
  });
  return (
    <Card compact style={{ marginTop: 8 }}>
      <VStack gap={8}>
        {url ? (
          // React Native has no audio element; on web the DOM one does the job.
          React.createElement("audio", {
            src: url,
            controls: true,
            autoPlay: true,
            style: { width: "100%" },
            "aria-label": "Round recording",
          })
        ) : (
          <Button
            label="Play recording"
            variant="secondary"
            size="sm"
            fullWidth={false}
            loading={access.isPending}
            onPress={() => access.mutate()}
          />
        )}
        {access.isError ? (
          <Banner tone="danger" message={apiErrorMessage(access.error)} />
        ) : null}
      </VStack>
    </Card>
  );
}

function Transcript({ interviewId, roundId }: { interviewId: string; roundId: string }) {
  const turns = useQuery({
    queryKey: ["interview-turns", interviewId, roundId],
    queryFn: () => interviewApi.turns(interviewId, roundId),
  });
  return (
    <Card style={{ marginTop: 8 }}>
      {turns.isLoading ? (
        <Skeleton height={80} />
      ) : turns.isError ? (
        <ErrorState error={turns.error} onRetry={() => void turns.refetch()} />
      ) : (
        <VStack gap={10}>
          <Text variant="label" tone="secondary">
            Transcript
          </Text>
          {(turns.data ?? []).map((t) => (
            <VStack key={t.id} gap={2}>
              <Text variant="overline" tone="tertiary">
                {t.speaker === "ai" ? "Interviewer" : "Candidate"}
              </Text>
              <Text variant="body-sm">{t.text}</Text>
            </VStack>
          ))}
        </VStack>
      )}
    </Card>
  );
}
